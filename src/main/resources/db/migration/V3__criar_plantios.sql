CREATE TABLE plantios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    talhao_id BIGINT NOT NULL REFERENCES talhoes(id),
    cultura_id BIGINT NOT NULL REFERENCES culturas(id),
    area_hectares NUMERIC(12,2) NOT NULL CHECK (area_hectares > 0),
    data_plantio DATE NOT NULL,
    previsao_colheita DATE NOT NULL,
    data_colheita DATE,
    CHECK (previsao_colheita >= data_plantio),
    CHECK (data_colheita IS NULL OR data_colheita >= data_plantio)
);
CREATE INDEX idx_plantios_talhao_ativos ON plantios(talhao_id) WHERE data_colheita IS NULL;
CREATE INDEX idx_plantios_cultura ON plantios(cultura_id);
